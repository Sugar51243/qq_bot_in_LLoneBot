// 当前语言：localStorage → 浏览器语言探测（zh-TW 等繁体 → zh-TW；其他 zh → zh-CN；其余 en）
let LANG = (function () {
  const saved = localStorage.getItem('xsw_lang');
  if (saved && I18N[saved]) return saved;
  const nav = String(navigator.language || 'zh-CN').toLowerCase();
  if (nav === 'zh-tw' || nav === 'zh-hk' || nav === 'zh-mo' || nav.startsWith('zh-hant')) return 'zh-TW';
  if (nav.startsWith('zh')) return 'zh-CN';
  return 'en';
})();

// 取文案；缺失回退 zh-CN，再缺失回退键名；{name} 参数插值
function t(key, params) {
  const dict = I18N[LANG] || I18N['zh-CN'];
  let s = dict[key] != null ? dict[key] : (I18N['zh-CN'][key] != null ? I18N['zh-CN'][key] : key);
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? params[k] : m));
  return s;
}

// 数字/时间格式化用的 locale
function locale() {
  return LANG === 'en' ? 'en-US' : LANG;
}

// 切换语言并即时生效（不刷新页面）
function setLang(lang) {
  if (!I18N[lang] || lang === LANG) return;
  LANG = lang;
  localStorage.setItem('xsw_lang', lang);
  document.documentElement.lang = lang;
  applyI18n();
}

// 应用翻译：静态属性 + 各页注册的动态重渲染回调
function applyI18n() {
  document.documentElement.classList.remove('i18n-pending');
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  document.querySelectorAll('.lang-select').forEach((el) => { el.value = LANG; });
  (window.__i18nRerender || []).forEach((fn) => {
    try { fn(); } catch (e) { console.error(e); }
  });
}

// 语言选择器：在每个 .lang-slot 容器内生成下拉框
function buildLangSelects() {
  document.querySelectorAll('.lang-slot').forEach((slot) => {
    const sel = document.createElement('select');
    sel.className = 'lang-select';
    sel.setAttribute('data-i18n-title', 'lang.title');
    for (const [code, name] of LANG_OPTIONS) {
      const o = document.createElement('option');
      o.value = code;
      o.textContent = name;
      sel.appendChild(o);
    }
    sel.value = LANG;
    sel.addEventListener('change', () => setLang(sel.value));
    slot.appendChild(sel);
  });
}

// 初始化：head 同步执行 → 设 <html lang>；非中文初始语言时先隐藏 body，DOM 就绪翻译后显示，避免闪中文
document.documentElement.lang = LANG;
window.__i18nRerender = window.__i18nRerender || [];
if (LANG !== 'zh-CN') document.documentElement.classList.add('i18n-pending');
document.addEventListener('DOMContentLoaded', () => {
  buildLangSelects();
  applyI18n();
});
